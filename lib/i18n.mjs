let lang =
  localStorage.getItem("esfera-language") ||
  (/^es\b/i.test(navigator.language) ? "es" : "en");
const originals = new WeakMap();
export const t = (text) => (lang === "en" ? pairs[text] || text : text);
export function translateLive(text) {
  const source = Object.keys(pairs).find((key) => pairs[key] === text) || text;
  return t(source);
}
export function setLanguage(value) {
  lang = value === "es" ? "es" : "en";
  localStorage.setItem("esfera-language", lang);
  document.documentElement.lang = lang;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (
      ["SCRIPT", "STYLE"].includes(node.parentElement?.tagName) ||
      node.parentElement?.closest(
        "#status,#hint,#imageInfo,#maskList,#stampList",
      )
    )
      continue;
    let original = originals.get(node);
    if (original === undefined) {
      original = node.nodeValue;
      originals.set(node, original);
    }
    const leading = original.match(/^\s*/)[0],
      trailing = original.match(/\s*$/)[0],
      clean = original.trim();
    if (pairs[clean]) node.nodeValue = leading + t(clean) + trailing;
  }
  for (const element of document.querySelectorAll(
    "[title],[aria-label],[placeholder]",
  ))
    for (const attribute of ["title", "aria-label", "placeholder"])
      if (element.hasAttribute(attribute)) {
        const key =
          "i18n" + attribute.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
        if (!element.dataset[key])
          element.dataset[key] = element.getAttribute(attribute);
        element.setAttribute(attribute, t(element.dataset[key]));
      }
  return lang;
}
export function language() {
  return lang;
}
